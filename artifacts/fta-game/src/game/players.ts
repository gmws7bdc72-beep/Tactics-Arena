export function getDefaultSquad(): PlayerCard[] {
  const starters = [
    ALL_PLAYERS.find((p) => p.id === "gk_neuer")!,
    ALL_PLAYERS.find((p) => p.id === "p4")!,
    ALL_PLAYERS.find((p) => p.id === "p7")!,
    ALL_PLAYERS.find((p) => p.id === "p3")!,
    ALL_PLAYERS.find((p) => p.id === "p5")!,
    ALL_PLAYERS.find((p) => p.id === "p1")!,
  ];
  const targetSize = getInitialSquadSize("player_team");
  const reserves = ALL_PLAYERS.filter(
    (player) => !starters.some((starter) => starter.id === player.id),
  ).slice(0, Math.max(0, targetSize - starters.length));

  return expandSquad([...starters, ...reserves], "player_team", 1, 1)
    .map((player, index) =>
      randomizePlayerForNewSave(player, "player_team", index),
    );
}

export function getGoalkeepers(): PlayerCard[] {
  return ALL_PLAYERS.filter((p) => p.role === "goalkeeper");
}

export function getOutfieldPlayers(): PlayerCard[] {
  return ALL_PLAYERS.filter((p) => p.role !== "goalkeeper");
}
